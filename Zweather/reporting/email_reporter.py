def _risk_badge_html(level: str | None) -> str:
    text = str(level or "unknown")
    cls = f"badge-{text.lower()}" if text.lower() in ("low", "medium", "high", "critical") else "badge-medium"
    return f'<span class="badge {cls}">{text}</span>'


def _build_report_html(
    results: dict[str, Any],
    region: str = "Midlands",
) -> str:
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    sections_html = ""

    for sector, analysis in results.items():
        risk = analysis.get("risk_level", "N/A")
        recs = analysis.get("recommendations", [])
        region_name = analysis.get("region", region)

        detail_rows = ""
        for k, v in analysis.items():
            if k in ("risk_level", "recommendations", "region", "season", "vessel", "facility_type",
                     "property_type", "aircraft", "asset", "transport_mode",
                     "vessel_name", "facility_name", "property_name", "aircraft_name",
                     "asset_name", "mode_name"):
                continue
            if isinstance(v, dict):
                for sk, sv in v.items():
                    if isinstance(sv, list):
                        detail_rows += f"<tr><td>{k}.{sk}</td><td>{', '.join(str(x) for x in sv[:3])}</td></tr>"
                    else:
                        detail_rows += f"<tr><td>{k}.{sk}</td><td>{sv}</td></tr>"
            elif isinstance(v, list):
                items = [str(x.get("risk", x.get("hazard", x.get("phase", str(x))))) for x in v[:5]]
                detail_rows += f"<tr><td>{k}</td><td>{', '.join(items)}</td></tr>"
            else:
                detail_rows += f"<tr><td>{k}</td><td>{v}</td></tr>"

        rec_html = "".join(f'<li class="rec">{r}</li>' for r in recs[:5]) if recs else ""

        section = f"""\
<div class="card">
  <h2>{sector.title()} — {_risk_badge_html(risk)}</h2>
  <table>
    <tr><th>Region</th><td>{region_name}</td></tr>
    {detail_rows}
  </table>
  {("<ul style='margin:8px 0 0 0;padding-left:20px'>" + rec_html + "</ul>") if rec_html else ""}
</div>
"""
        sections_html += section

    return _HTML_TEMPLATE.format(timestamp=timestamp, region=region, sections=sections_html)


def send_report(
    results: dict[str, Any],
    region: str = "Midlands",
    config: EmailConfig | None = None,
) -> bool:
    cfg = config or _load_config_from_env()
    if not cfg.to_addrs:
        logger.warning("No SMTP_TO recipients configured. Skipping email.")
        return False

    html = _build_report_html(results, region)

    msg = MIMEMultipart("alternative")
    msg["Subject"] = f"Zedd Weather Report — {datetime.now(timezone.utc).strftime('%Y-%m-%d')}"
    msg["From"] = cfg.from_addr
    msg["To"] = ", ".join(cfg.to_addrs)
    msg.attach(MIMEText(html, "html"))

    try:
        with smtplib.SMTP(cfg.smtp_host, cfg.smtp_port) as server:
            if cfg.use_tls:
                server.starttls()
            if cfg.smtp_user and cfg.smtp_password:
                server.login(cfg.smtp_user, cfg.smtp_password)
            server.sendmail(cfg.from_addr, cfg.to_addrs, msg.as_string())
        logger.info("Report sent to %s", cfg.to_addrs)
        return True
    except Exception as exc:
        logger.exception("Failed to send report: %s", exc)
        return False


def send_sector_report(
    sector: str,
    analysis: dict[str, Any],
    config: EmailConfig | None = None,
) -> bool:
    return send_report({sector: analysis}, region=analysis.get("region", "Midlands"), config=config)
