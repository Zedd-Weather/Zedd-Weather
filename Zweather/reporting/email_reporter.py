"""
Zedd Weather — Email Reporter
Sends HTML-formatted weather risk reports via SMTP.
"""
from __future__ import annotations

import logging
import os
import smtplib
from dataclasses import dataclass, field
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from datetime import datetime, timezone
from typing import Any

logger = logging.getLogger(__name__)


@dataclass
class EmailConfig:
    smtp_host: str = "localhost"
    smtp_port: int = 587
    smtp_user: str | None = None
    smtp_password: str | None = None
    use_tls: bool = True
    from_addr: str = "zedd-weather@localhost"
    to_addrs: list[str] = field(default_factory=list)


def _load_config_from_env() -> EmailConfig:
    return EmailConfig(
        smtp_host=os.getenv("SMTP_HOST", "localhost"),
        smtp_port=int(os.getenv("SMTP_PORT", "587")),
        smtp_user=os.getenv("SMTP_USER") or None,
        smtp_password=os.getenv("SMTP_PASSWORD") or None,
        use_tls=os.getenv("SMTP_USE_TLS", "true").lower() == "true",
        from_addr=os.getenv("SMTP_FROM", "zedd-weather@localhost"),
        to_addrs=[a.strip() for a in os.getenv("SMTP_TO", "").split(",") if a.strip()],
    )


